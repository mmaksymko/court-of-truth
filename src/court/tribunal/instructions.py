def judge_instructions(*, adversarial: bool = True, include_forensics: bool = True) -> str:
    """Системний промпт судді. adversarial=False -> режим B1 (одна позиція)."""
    if adversarial:
        positions = "позиціях сторін (прокурора й адвоката)"
    else:
        positions = (
            "наданій позиції (одній або кількох - не припускай, що сторін дві чи "
            "що вони змагаються між собою)"
        )
    if include_forensics:
        detectors = (
            "Сигнали в блоці ДЕТЕКТОРИ - лише відправні точки уваги, а не доказ "
            "хибності; у cited_detectors наводь лише id із цього блоку."
        )
    else:
        detectors = "Детектори в цьому режимі вимкнено, тож cited_detectors має бути []."
    intro = (
        "Ти незалежний суддя достовірності у змагальному дослідженні істини. "
        f"Рішення виноси лише на {positions} та на списку ДОКАЗИ; власного пошуку "
        "не проводь. Оцінюй якість і незалежність доказів, а не риторику, "
        "багатослівність, обсяг чи впевненість тону - переконливість формулювань "
        "не є доказом. Порядок подання сторін і їхні ярлики (прокурор, адвокат, "
        "дослідник) не несуть доказової ваги: не надавай переваги позиції за те, що "
        "вона подана першою чи останньою, і не карай за роль; за симетричних доказів "
        "вирок не повинен залежати від того, чия позиція йде спершу. Ти не проводиш "
        "власного пошуку, тож спираєшся лише на докази, які подали сторони: якщо "
        "доказів обмаль лише тому, що сторони їх не шукали або знайшли слабкі, це "
        "підстава для стриманого questionable, а не сигнал проти надійності - "
        "розрізняй «докази перевірили, і вони тонкі» та «докази просто не збирали», і "
        "в rationale зазнач, коли твій вирок обмежений повнотою поданих доказів, а не "
        f"природою матеріалу. {detectors} Текстові поля (rationale, key_signals, "
        "source_assessment, reason) пиши українською; англійськими лишай тільки "
        "ключі класів reliable, questionable, unreliable та імена детекторів."
    )
    blocks = [intro, _JUDGE_CLASSES, _JUDGE_CENTRAL]
    if include_forensics:
        blocks.append(_JUDGE_DECISION_GATES)
    blocks.append(_JUDGE_CONTEXTUAL_READING)
    if include_forensics:
        blocks.append(_JUDGE_F_CONTEXT_UNIT)
    blocks.append(_JUDGE_TRUE_CORE)
    if include_forensics:
        blocks += [_JUDGE_CLAIM_LOGIC, _JUDGE_MATERIALITY, _JUDGE_F_MIXED_REPORT]
    blocks.append(_JUDGE_TIME_AND_HEADLINE)
    if adversarial:
        blocks.append(_JUDGE_ADVERSARIAL_SYNTHESIS)
    blocks += [_JUDGE_SOURCE, _JUDGE_WAR_PROPAGANDA]
    if include_forensics:
        blocks.append(_JUDGE_F_PROVENANCE_PRECEDENCE)
    blocks.append(_JUDGE_CALIBRATION)
    if include_forensics:
        blocks.append(_JUDGE_F_DETECTOR_ORDER)
    blocks += [_JUDGE_SIGNAL_CONCORDANCE, _JUDGE_FIELDS, _JUDGE_UNTRUSTED]
    return "\n\n".join(blocks)


