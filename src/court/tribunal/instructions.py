def party_instructions(
    role: Role, *, include_forensics: bool = True, include_search: bool = True
) -> str:
    """Системний промпт сторони: спільний префікс + роль у кінці (для кешу).

    include_forensics=False (режим B2) повністю прибирає блок критеріїв
    детекторів. include_search=False (режим B3) замінює протокол пошуку блоком
    без зовнішнього пошуку: сторона аргументує лише зі статті й детекторів.
    """
    blocks = [_MISSION, _INDEPENDENCE]
    if include_forensics:
        blocks.append(_SIGNALS)
    blocks.append(_SEARCH if include_search else _NO_SEARCH)
    blocks += [_CLAIMS, _CONTRARY, _UNTRUSTED_PARTY, _ROLE_TEXT[role]]
    return "\n\n".join(blocks)


